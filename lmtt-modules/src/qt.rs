use lmtt_core::{colors::hex_to_rgb, ColorScheme, Config, Result};
use std::path::{Path, PathBuf};

crate::register_module!(QtModule);

pub struct QtModule;

impl Default for QtModule {
    fn default() -> Self {
        Self::new()
    }
}

impl QtModule {
    pub fn new() -> Self {
        Self
    }
}

/// QPalette ColorRole order used by qt6ct (22 roles through Accent).
const PALETTE_KEYS: [&str; 22] = [
    "on_surface",                // WindowText
    "surface_container",         // Button
    "surface_container_highest", // Light
    "surface_container_high",    // Midlight
    "outline",                   // Dark
    "outline_variant",           // Mid
    "on_surface",                // Text
    "on_primary",                // BrightText
    "on_surface",                // ButtonText
    "surface",                   // Base
    "surface",                   // Window
    "shadow",                    // Shadow
    "primary",                   // Highlight
    "on_primary",                // HighlightedText
    "primary",                   // Link
    "secondary",                 // LinkVisited
    "surface_container_low",     // AlternateBase
    "surface",                   // NoRole
    "inverse_surface",           // ToolTipBase
    "inverse_on_surface",        // ToolTipText
    "outline",                   // PlaceholderText
    "primary",                   // Accent
];

/// The colour scheme LMTT owns, relative to the qt6ct config directory.
const OWNED_SCHEME: &str = "colors/lmtt.conf";

/// Palette indices whose disabled colour is dimmed text, not the active one.
const DISABLED_TEXT_ROLES: [usize; 3] = [0, 6, 8]; // WindowText, Text, ButtonText

/// Material's disabled-content opacity.
const DISABLED_TEXT_ALPHA: f32 = 0.38;

fn rgb(scheme: &ColorScheme, key: &str) -> (u8, u8, u8) {
    hex_to_rgb(&scheme.get_or_fallback(key)).unwrap_or((0x80, 0x80, 0x80))
}

fn hex((r, g, b): (u8, u8, u8)) -> String {
    format!("#{:02x}{:02x}{:02x}", r, g, b)
}

/// `fg` at `alpha` over `bg`, flattened so qt6ct gets an opaque colour.
fn over(fg: (u8, u8, u8), bg: (u8, u8, u8), alpha: f32) -> (u8, u8, u8) {
    let mix = |f: u8, b: u8| (f as f32 * alpha + b as f32 * (1.0 - alpha)).round() as u8;
    (mix(fg.0, bg.0), mix(fg.1, bg.1), mix(fg.2, bg.2))
}

fn active_palette(scheme: &ColorScheme) -> Vec<String> {
    PALETTE_KEYS
        .iter()
        .map(|key| hex(rgb(scheme, key)))
        .collect()
}

fn disabled_palette(scheme: &ColorScheme) -> Vec<String> {
    let dimmed = hex(over(
        rgb(scheme, "on_surface"),
        rgb(scheme, "surface"),
        DISABLED_TEXT_ALPHA,
    ));
    let mut palette = active_palette(scheme);
    for role in DISABLED_TEXT_ROLES {
        palette[role] = dimmed.clone();
    }
    palette
}

fn color_scheme_file(scheme: &ColorScheme) -> String {
    let active = active_palette(scheme).join(", ");
    let disabled = disabled_palette(scheme).join(", ");
    format!(
        "# generated by lmtt, do not edit\n\
         # Mode: {}\n\
         [ColorScheme]\n\
         active_colors={active}\n\
         disabled_colors={disabled}\n\
         inactive_colors={active}\n",
        scheme.mode
    )
}

fn qt6ct_dir(config_home: &Path) -> PathBuf {
    config_home.join("qt6ct")
}

fn config_home() -> Result<PathBuf> {
    dirs::config_dir().ok_or_else(|| lmtt_core::Error::Config("No config dir".into()))
}

/// Writes the owned scheme to `$XDG_CONFIG_HOME/qt6ct/colors/lmtt.conf`.
async fn write_owned_scheme(config_home: &Path, scheme: &ColorScheme) -> Result<PathBuf> {
    let path = qt6ct_dir(config_home).join(OWNED_SCHEME);
    if let Some(dir) = path.parent() {
        tokio::fs::create_dir_all(dir).await?;
    }
    lmtt_core::fsutil::write_atomic(&path, color_scheme_file(scheme)).await?;
    Ok(path)
}

/// Points qt6ct.conf's [Appearance] at the owned scheme. Other keys and
/// sections (Fonts, Interface) stay the user's.
async fn merge_appearance(config_home: &Path, scheme_path: &Path, icon_theme: &str) -> Result<()> {
    let conf_path = qt6ct_dir(config_home).join("qt6ct.conf");
    let current = tokio::fs::read_to_string(&conf_path)
        .await
        .unwrap_or_default();
    let updates = [
        (
            "color_scheme_path",
            scheme_path.to_string_lossy().into_owned(),
        ),
        ("custom_palette", "true".to_string()),
        ("style", "Fusion".to_string()),
        ("icon_theme", icon_theme.to_string()),
    ];
    let merged = gtk::merge_ini(&current, "Appearance", &updates);
    lmtt_core::fsutil::write_atomic(&conf_path, merged).await
}

async fn current_icon_theme() -> String {
    let output = tokio::process::Command::new("gsettings")
        .args(["get", "org.gnome.desktop.interface", "icon-theme"])
        .output()
        .await;
    match output {
        Ok(o) if o.status.success() => String::from_utf8_lossy(&o.stdout)
            .trim()
            .trim_matches('\'')
            .to_string(),
        _ => "Adwaita".to_string(),
    }
}

async fn platform_theme_is_qt6ct() -> bool {
    if let Ok(val) = std::env::var("QT_QPA_PLATFORMTHEME") {
        return val == "qt6ct";
    }
    session_env_has_platformtheme_value("qt6ct").await
}

async fn session_env_has_any_platformtheme() -> bool {
    let Ok(output) = tokio::process::Command::new("systemctl")
        .args(["--user", "show-environment"])
        .output()
        .await
    else {
        return false;
    };
    output.status.success()
        && String::from_utf8_lossy(&output.stdout)
            .lines()
            .any(|line| line.starts_with("QT_QPA_PLATFORMTHEME="))
}

async fn session_env_has_platformtheme_value(want: &str) -> bool {
    let Ok(output) = tokio::process::Command::new("systemctl")
        .args(["--user", "show-environment"])
        .output()
        .await
    else {
        return false;
    };
    if !output.status.success() {
        return false;
    }
    String::from_utf8_lossy(&output.stdout)
        .lines()
        .any(|line| line == format!("QT_QPA_PLATFORMTHEME={want}"))
}

#[async_trait]
impl ThemeModule for QtModule {
    fn name(&self) -> &'static str {
        "qt"
    }

    fn binary_name(&self) -> &'static str {
        "qt6ct"
    }

    fn priority(&self) -> u8 {
        20
    }

    async fn apply(&self, scheme: &ColorScheme, _config: &Config) -> Result<()> {
        let config_home = config_home()?;
        let scheme_path = write_owned_scheme(&config_home, scheme).await?;

        // kvantum/qt5ct users win if they already set a platform theme that
        // is not qt6ct. hypr-DE's uwsm env sets qt6ct, so the common path
        // merges Appearance and leaves Fonts/Interface alone.
        let already_set = std::env::var("QT_QPA_PLATFORMTHEME").is_ok()
            || session_env_has_any_platformtheme().await;
        if !already_set {
            let env_commands = vec![
                (
                    "systemctl",
                    vec!["--user", "set-environment", "QT_QPA_PLATFORMTHEME=qt6ct"],
                ),
                (
                    "dbus-update-activation-environment",
                    vec!["--systemd", "QT_QPA_PLATFORMTHEME=qt6ct"],
                ),
            ];

            for (cmd, args) in env_commands {
                if which::which(cmd).is_err() {
                    continue;
                }
                let result = tokio::process::Command::new(cmd).args(&args).output().await;
                match result {
                    Ok(output) if !output.status.success() => {
                        tracing::warn!(
                            "[Qt] {} failed: {}",
                            cmd,
                            String::from_utf8_lossy(&output.stderr).trim()
                        );
                    }
                    Err(e) => tracing::warn!("[Qt] {} failed to run: {}", cmd, e),
                    _ => {}
                }
            }

            if which::which("hyprctl").is_ok() {
                let _ = tokio::process::Command::new("hyprctl")
                    .args(["setenv", "QT_QPA_PLATFORMTHEME", "qt6ct"])
                    .output()
                    .await;
            }
            tracing::info!("[Qt] Exported QT_QPA_PLATFORMTHEME=qt6ct for new processes");
        } else {
            tracing::debug!("[Qt] QT_QPA_PLATFORMTHEME already set, leaving session env alone");
        }

        if platform_theme_is_qt6ct().await || !already_set {
            merge_appearance(&config_home, &scheme_path, &current_icon_theme().await).await?;
            tracing::info!(
                "[Qt] Wrote {} palette and merged qt6ct Appearance",
                scheme.mode
            );
        }

        Ok(())
    }

    async fn config_files(&self) -> Result<Vec<ConfigFileInfo>> {
        let conf = qt6ct_dir(&config_home()?).join("qt6ct.conf");
        Ok(vec![ConfigFileInfo {
            path: conf,
            include_line: String::new(),
            description: "LMTT writes [Appearance] (palette path, Fusion, icons); Fonts stay yours"
                .to_string(),
            already_included: true,
        }])
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use lmtt_core::ThemeMode;

    fn scheme() -> ColorScheme {
        let mut s = ColorScheme::new(ThemeMode::Dark);
        s.set("primary".into(), "#ffb77a".into());
        s.set("on_primary".into(), "#19120c".into());
        s.set("surface".into(), "#19120c".into());
        s.set("on_surface".into(), "#efe0d6".into());
        s
    }

    /// The row for `key` in a written colour scheme, split into its roles.
    fn row(body: &str, key: &str) -> Vec<String> {
        let prefix = format!("{key}=");
        let line = body
            .lines()
            .find_map(|l| l.strip_prefix(&prefix))
            .unwrap_or_else(|| panic!("no {key} in {body}"));
        line.split(", ").map(str::to_string).collect()
    }

    fn rt() -> tokio::runtime::Runtime {
        tokio::runtime::Builder::new_current_thread()
            .enable_all()
            .build()
            .unwrap()
    }

    #[test]
    fn owned_scheme_is_written_under_xdg_config_home() {
        let config_home = tempfile::tempdir().unwrap();
        let path = rt()
            .block_on(write_owned_scheme(config_home.path(), &scheme()))
            .unwrap();

        assert_eq!(path, config_home.path().join("qt6ct/colors/lmtt.conf"));
        let body = std::fs::read_to_string(&path).unwrap();
        assert!(body.contains("[ColorScheme]"), "{body}");
        for key in ["active_colors", "disabled_colors", "inactive_colors"] {
            let roles = row(&body, key);
            assert_eq!(roles.len(), PALETTE_KEYS.len(), "{key}: {roles:?}");
            assert!(roles.iter().all(|c| c.len() == 7 && c.starts_with('#')));
        }
        let active = row(&body, "active_colors");
        assert_eq!(active[0], "#efe0d6"); // WindowText = on_surface
        assert_eq!(active[10], "#19120c"); // Window = surface
        assert_eq!(active[12], "#ffb77a"); // Highlight = primary
        assert_eq!(row(&body, "inactive_colors"), active);

        let leftovers: Vec<_> = std::fs::read_dir(path.parent().unwrap())
            .unwrap()
            .map(|e| e.unwrap().file_name())
            .collect();
        assert_eq!(leftovers, ["lmtt.conf"], "temp file left behind");
    }

    #[test]
    fn disabled_text_is_dimmed_toward_the_surface() {
        let body = color_scheme_file(&scheme());
        let active = row(&body, "active_colors");
        let disabled = row(&body, "disabled_colors");
        for role in DISABLED_TEXT_ROLES {
            assert_ne!(disabled[role], active[role], "role {role}");
            // 38% of #efe0d6 over #19120c.
            assert_eq!(disabled[role], "#6a6059", "role {role}");
        }
        for role in (0..PALETTE_KEYS.len()).filter(|r| !DISABLED_TEXT_ROLES.contains(r)) {
            assert_eq!(disabled[role], active[role], "role {role}");
        }
    }

    #[test]
    fn appearance_points_at_owned_scheme_and_keeps_user_keys() {
        let config_home = tempfile::tempdir().unwrap();
        let conf = config_home.path().join("qt6ct/qt6ct.conf");
        std::fs::create_dir_all(conf.parent().unwrap()).unwrap();
        std::fs::write(
            &conf,
            "[Appearance]\ncolor_scheme_path=/usr/share/qt6ct/colors/darker.conf\n\
             custom_palette=false\nstandard_dialogs=xdgdesktopportal\nstyle=Windows\n\n\
             [Fonts]\nfixed=\"Noto Sans Mono,10\"\n\n[Interface]\ndouble_click_interval=400\n",
        )
        .unwrap();

        let rt = rt();
        let scheme_path = rt
            .block_on(write_owned_scheme(config_home.path(), &scheme()))
            .unwrap();
        rt.block_on(merge_appearance(
            config_home.path(),
            &scheme_path,
            "Papirus",
        ))
        .unwrap();
        let once = std::fs::read_to_string(&conf).unwrap();

        let expected = format!("color_scheme_path = {}", scheme_path.display());
        assert!(once.contains(&expected), "{once}");
        assert!(expected.ends_with("qt6ct/colors/lmtt.conf"));
        assert!(once.contains("custom_palette = true"), "{once}");
        assert!(once.contains("style = Fusion"), "{once}");
        assert!(once.contains("icon_theme = Papirus"), "{once}");
        assert!(once.contains("standard_dialogs=xdgdesktopportal"), "{once}");
        assert!(
            once.contains("[Fonts]\nfixed=\"Noto Sans Mono,10\""),
            "{once}"
        );
        assert!(once.contains("double_click_interval=400"), "{once}");
        assert!(!once.contains("darker.conf"), "{once}");
        assert!(!once.contains("custom_palette=false"), "{once}");
        assert!(!once.contains("Windows"), "{once}");

        rt.block_on(merge_appearance(
            config_home.path(),
            &scheme_path,
            "Papirus",
        ))
        .unwrap();
        assert_eq!(
            std::fs::read_to_string(&conf).unwrap(),
            once,
            "not idempotent"
        );
    }

    #[test]
    fn appearance_merge_creates_missing_conf() {
        let config_home = tempfile::tempdir().unwrap();
        let rt = rt();
        let scheme_path = rt
            .block_on(write_owned_scheme(config_home.path(), &scheme()))
            .unwrap();
        rt.block_on(merge_appearance(
            config_home.path(),
            &scheme_path,
            "Adwaita",
        ))
        .unwrap();
        let conf = std::fs::read_to_string(config_home.path().join("qt6ct/qt6ct.conf")).unwrap();
        assert!(conf.starts_with("[Appearance]\n"), "{conf}");
        assert!(conf.contains("custom_palette = true"), "{conf}");
    }
}
